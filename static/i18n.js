  const storage = root.document ? root.localStorage : null;
  let locale = DEFAULT_LOCALE;
  try {
    const saved = storage && storage.getItem(STORAGE_KEY);
    if (SUPPORTED_LOCALES.includes(saved)) locale = saved;
  } catch (_) {}

  function interpolate(message, values = {}) {
    return String(message).replace(/\{([a-z_]+)\}/gi, (_, key) =>
      Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : `{${key}}`
    );
  }

  function t(key, values = {}) {
    const message = MESSAGES[locale][key] ?? MESSAGES[DEFAULT_LOCALE][key] ?? key;
    return interpolate(message, values);
  }

  function getLocale() { return locale; }

  function applyStatic(doc = root.document) {
    if (!doc) return;
    doc.documentElement.lang = locale;
    doc.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
    doc.querySelectorAll('[data-i18n-title]').forEach(node => { node.title = t(node.dataset.i18nTitle); });
    doc.querySelectorAll('[data-i18n-aria]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAria)); });
    doc.querySelectorAll('[data-i18n-placeholder]').forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  }

  function setLocale(next, options = {}) {
    if (!SUPPORTED_LOCALES.includes(next)) return locale;
    locale = next;
    if (options.persist !== false) {
      try { storage && storage.setItem(STORAGE_KEY, locale); } catch (_) {}
    }
    applyStatic(options.document || root.document);
    return locale;
  }

  const api = {DEFAULT_LOCALE, SUPPORTED_LOCALES, STORAGE_KEY, MESSAGES, interpolate, t, getLocale, setLocale, applyStatic};
  root.DirectorsRoomI18n = api;
